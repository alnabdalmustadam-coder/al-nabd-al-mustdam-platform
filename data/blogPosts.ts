export function getAllBlogPosts(): BlogPost[] {
  return blogPosts;
}

export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  const cleanSlug = slug.toLowerCase().trim();
  return blogPosts.find((p) => p.slug.toLowerCase() === cleanSlug || String(p.id) === cleanSlug);
}

export function getRelatedBlogPosts(currentSlug: string, count: number = 2): BlogPost[] {
  const cleanSlug = currentSlug.toLowerCase().trim();
  return blogPosts.filter((p) => p.slug.toLowerCase() !== cleanSlug).slice(0, count);
}
