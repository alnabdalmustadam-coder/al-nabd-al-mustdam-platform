ALTER TABLE public.course_entitlements ENABLE ROW LEVEL SECURITY;

CREATE POLICY course_catalog_public_read ON public.course_catalog FOR SELECT
  USING (status = 'published' OR public.is_admin() OR public.is_instructor());
CREATE POLICY course_catalog_staff_manage ON public.course_catalog FOR ALL TO authenticated
  USING (public.is_admin() OR public.is_instructor())
  WITH CHECK (public.is_admin() OR public.is_instructor());

CREATE POLICY certificate_templates_authenticated_read ON public.certificate_templates FOR SELECT TO authenticated
  USING (true);
CREATE POLICY certificate_templates_admin_manage ON public.certificate_templates FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

CREATE POLICY admin_content_public_read ON public.admin_content_items FOR SELECT
  USING (
    (kind = 'article' AND status = 'published')
    OR (kind = 'service' AND status = 'active')
    OR public.is_admin()
  );
CREATE POLICY admin_content_admin_manage ON public.admin_content_items FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

CREATE POLICY admin_audit_admin_read ON public.admin_audit_log FOR SELECT TO authenticated
  USING (public.is_admin());

CREATE POLICY admin_notifications_admin_access ON public.admin_notifications FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

CREATE POLICY entitlements_own_or_admin_read ON public.course_entitlements FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR LOWER(email) = LOWER(auth.jwt() ->> 'email') OR public.is_admin());
CREATE POLICY entitlements_admin_manage ON public.course_entitlements FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

