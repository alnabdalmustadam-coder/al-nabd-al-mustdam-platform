// Optional isolated PostgreSQL check; no production connection or credentials.
// Install @electric-sql/pglite in a temporary directory, then run:
// node supabase/tests/course-instructor-ownership.mjs /absolute/path/to/pglite/dist/index.js
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const { PGlite } = await import(process.argv[2] || '@electric-sql/pglite');
const db = await PGlite.create();
const owner = '00000000-0000-4000-8000-000000000001';
const other = '00000000-0000-4000-8000-000000000002';
let checks = 0;
const equal = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks++; };

try {
  await db.exec(`
    CREATE ROLE anon NOLOGIN;
    CREATE ROLE authenticated NOLOGIN;
    CREATE ROLE service_role NOLOGIN BYPASSRLS;
    CREATE SCHEMA auth;
    GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role;
    CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
      SELECT COALESCE(NULLIF(current_setting('request.jwt.claims', true), ''), '{}')::jsonb
    $$;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT (auth.jwt() ->> 'sub')::uuid $$;
    CREATE FUNCTION public.is_admin() RETURNS boolean LANGUAGE sql STABLE AS $$
      SELECT UPPER(COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', 'STUDENT')) IN ('ADMIN','SUPERADMIN','SUPER_ADMIN')
    $$;
    CREATE FUNCTION public.is_instructor() RETURNS boolean LANGUAGE sql STABLE AS $$
      SELECT UPPER(COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', 'STUDENT')) IN ('INSTRUCTOR','TRAINER','TEACHER')
    $$;
    CREATE TABLE public.course_catalog (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      slug text UNIQUE NOT NULL,
      title text NOT NULL,
      status text NOT NULL DEFAULT 'published',
      payload jsonb NOT NULL DEFAULT '{}'::jsonb
    );
    GRANT SELECT ON public.course_catalog TO anon;
    GRANT ALL ON public.course_catalog TO authenticated, service_role;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated, service_role;
    ALTER TABLE public.course_catalog ENABLE ROW LEVEL SECURITY;
    CREATE POLICY course_catalog_public_read ON public.course_catalog FOR SELECT USING (true);
    CREATE POLICY course_catalog_staff_manage ON public.course_catalog FOR ALL TO authenticated USING (true) WITH CHECK (true);
    -- An unexpected historical policy must not reopen access after migration.
    CREATE POLICY historical_broad_staff_policy ON public.course_catalog FOR ALL TO authenticated USING (true) WITH CHECK (true);
    INSERT INTO public.course_catalog (slug, title, status, payload) VALUES
      ('own-draft', 'Own draft', 'draft', '{"trainerId":"${owner}"}'),
      ('other-draft', 'Other draft', 'draft', '{"trainerId":"${other}"}'),
      ('public-course', 'Public course', 'published', '{"trainerId":"${other}"}'),
      ('unassigned-draft', 'Unassigned draft', 'draft', '{}');
  `);
  const migration = await readFile(new URL('../migrations/20260909_course_instructor_ownership.sql', import.meta.url), 'utf8');
  await db.exec(migration);
  await db.exec(migration); // Must be safe to apply again.

  async function asRole(databaseRole, appRole, action) {
    await db.query("SELECT set_config('request.jwt.claims', $1, false)", [JSON.stringify({ sub: owner, app_metadata: { role: appRole }, user_metadata: { role: 'ADMIN' } })]);
    await db.exec(`SET ROLE ${databaseRole}`);
    try { await action(); } finally { await db.exec('RESET ROLE'); }
  }
  async function cannotInsert(slug) {
    await assert.rejects(
      db.query("INSERT INTO public.course_catalog (slug, title, payload) VALUES ($1, 'Unauthorized', $2)", [slug, JSON.stringify({ trainerId: owner })]),
      error => error.code === '42501',
    );
    checks++;
  }

  for (const appRole of ['INSTRUCTOR', 'TRAINER', 'TEACHER']) {
    await asRole('authenticated', appRole, async () => {
      equal((await db.query('SELECT slug FROM public.course_catalog ORDER BY slug')).rows.map(row => row.slug), ['own-draft', 'public-course'], `${appRole}: visibility`);
      for (const slug of ['own-draft', 'other-draft', 'unassigned-draft', 'public-course']) {
        equal((await db.query("UPDATE public.course_catalog SET title = 'Unauthorized' WHERE slug = $1 RETURNING id", [slug])).rows.length, 0, `${appRole}: direct update denied`);
        equal((await db.query('DELETE FROM public.course_catalog WHERE slug = $1 RETURNING id', [slug])).rows.length, 0, `${appRole}: direct delete denied`);
      }
      await cannotInsert(`blocked-${appRole}`);
    });
  }
  await asRole('authenticated', 'STUDENT', async () => {
    equal((await db.query('SELECT slug FROM public.course_catalog')).rows.map(row => row.slug), ['public-course'], 'Student cannot claim staff rights through user_metadata');
    await cannotInsert('blocked-student');
  });
  await asRole('anon', 'STUDENT', async () => {
    equal((await db.query('SELECT slug FROM public.course_catalog')).rows.map(row => row.slug), ['public-course'], 'Anonymous published catalog remains readable');
  });
  for (const appRole of ['ADMIN', 'SUPERADMIN', 'SUPER_ADMIN']) {
    await asRole('authenticated', appRole, async () => {
      equal((await db.query('SELECT count(*)::int AS count FROM public.course_catalog')).rows[0].count, 4, `${appRole}: all courses visible`);
      equal((await db.query("UPDATE public.course_catalog SET title = 'Admin edit' WHERE slug = 'other-draft' RETURNING id")).rows.length, 1, `${appRole}: can edit another instructor course`);
      await db.query("INSERT INTO public.course_catalog (slug, title) VALUES ($1, 'Admin course')", [`admin-${appRole}`]);
      equal((await db.query('DELETE FROM public.course_catalog WHERE slug = $1 RETURNING id', [`admin-${appRole}`])).rows.length, 1, `${appRole}: can create and delete`);
    });
  }
  await asRole('service_role', 'STUDENT', async () => {
    await db.query("INSERT INTO public.course_catalog (slug, title) VALUES ('server-created', 'Server created')");
    equal((await db.query("UPDATE public.course_catalog SET title = 'Server edit' WHERE slug = 'server-created' RETURNING id")).rows.length, 1, 'Authenticated server write path remains available');
    equal((await db.query("DELETE FROM public.course_catalog WHERE slug = 'server-created' RETURNING id")).rows.length, 1, 'Authenticated server delete remains available');
  });
  console.log(`PostgreSQL RLS validation passed: ${checks} checks; migration applied twice successfully.`);
} finally {
  await db.close();
}
